def A(key, value, unit=None):
    a = {'key': key, 'value': str(value)}
    if unit: a['unit'] = unit
    return a

# Qisqartmalar
def P(v):  return A('Мощность', v, 'Вт')
def H(v):  return A('Максимальный напор', v, 'м')
def Q3(v): return A('Пропускная способность', v, 'м³/ч')
def QL(v): return A('Пропускная способность', v, 'л/мин')
def RPM(v):return A('Частота вращения', v, 'об/мин')
def SUC(v):return A('Высота всасывания', v, 'м')
def D(v):  return A('Диаметр отверстия', v, 'мм')
def V(v):  return A('Напряжение', v, 'В')
def AMP(v):return A('Ампераж', v, 'А')
def HZ(v=50): return A('Частота тока', v, 'Гц')
def IP(v): return A('Класс защиты', v)
def MAT(v):return A('Материал', v)
def LINE(v):return A('Модель', v)
def GW(v): return A('Вес брутто', v, 'кг')
def NW(v): return A('Вес нетто', v, 'кг')

